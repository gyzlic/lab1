class Vehicle:
    """
    Класс, представляющий транспортное средство.

    Атрибуты:
        brand (str): Марка транспортного средства.
        model (str): Модель транспортного средства.
    """

    def __init__(self, brand: str, model: str) -> None:
        """
        Инициализация транспортного средства с маркой и моделью.

        Параметры:
            brand (str): Марка транспортного средства.
            model (str): Модель транспортного средства.
        """
        self.brand = brand
        self.model = model

    def __str__(self) -> str:
        """
        Возвращает строковое представление транспортного средства.

        Возвращаемое значение:
            str: Строковое представление транспортного средства в формате "Марка Модель".
        """
        return f"Vehicle: {self.brand} {self.model}"

    def __repr__(self) -> str:
        """
        Возвращает строковое представление для использования в коде.

        Возвращаемое значение:
            str: Строковое представление объекта для отладки, например, "Vehicle('Марка', 'Модель')".
        """
        return f"Vehicle('{self.brand}', '{self.model}')"

    def display_info(self) -> str:
        """
        Отображает информацию о транспортном средстве.

        Возвращаемое значение:
            str: Информация о транспортном средстве в формате строки.
        """
        return str(self)

    def honk(self) -> str:
        """
        Издает стандартный сигнал для любого транспортного средства.

        Возвращаемое значение:
            str: Сигнал "Beep! Beep!".
        """
        return "Beep! Beep!"


class Car(Vehicle):
    """
    Класс, представляющий автомобиль, наследующий от класса Vehicle.

    Атрибуты:
        brand (str): Марка автомобиля.
        model (str): Модель автомобиля.
        seats (int): Количество сидений в автомобиле.
    """

    def __init__(self, brand: str, model: str, seats: int) -> None:
        """
        Инициализация автомобиля с маркой, моделью и количеством сидений.

        Параметры:
            brand (str): Марка автомобиля.
            model (str): Модель автомобиля.
            seats (int): Количество сидений в автомобиле.
        """
        super().__init__(brand, model)
        self.seats = seats

    def __str__(self) -> str:
        """
        Возвращает строковое представление автомобиля.

        Возвращаемое значение:
            str: Строковое представление автомобиля в формате "Марка Модель, Seats: Количество сидений".
        """
        return f"Car: {self.brand} {self.model}, Seats: {self.seats}"

    def __repr__(self) -> str:
        """
        Возвращает строковое представление для использования в коде.

        Возвращаемое значение:
            str: Строковое представление объекта для отладки, например, "Car('Марка', 'Модель', Количество сидений)".
        """
        return f"Car('{self.brand}', '{self.model}', {self.seats})"

    def display_info(self) -> str:
        """
        Отображает информацию об автомобиле.

        Возвращаемое значение:
            str: Информация об автомобиле в формате строки.
        """
        return str(self)

    def honk(self) -> str:
        """
        Издает сигнализацию автомобиля, отличающуюся от стандартного сигнала транспортного средства.

        Возвращаемое значение:
            str: Сигнал "Car horn: Honk! Honk!".
        """
        return "Car horn: Honk! Honk!"


# Пример использования
car = Car("Lexus", "GX470", 7)
print(car.display_info())  # Car: Toyota Camry, Seats: 5
print(car.honk())  # Car horn: Honk! Honk!
